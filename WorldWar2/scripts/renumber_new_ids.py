#!/usr/bin/env python3
"""Renumber unpublished ids on this branch that collide with a base revision.

  python scripts/renumber_new_ids.py                  dry-run against origin/main
  python scripts/renumber_new_ids.py --base <rev>     compare with any revision
  python scripts/renumber_new_ids.py --apply          write the remapping
  python scripts/renumber_new_ids.py --keep-group G318
  python scripts/renumber_new_ids.py --root DIR       dataset root (default: this WorldWar2 directory)

After a rebase onto an updated main, two pull requests that took the same
next-free ids leave this branch with rows whose ids already identify different
rows on main. For conflict groups, new claims on this branch can also silently
join a group that landed on main first (the id checks allow a group to gain
members). This script remaps only those unpublished rows to the next free ids
and rewrites references in the new or changed data rows, and in lines this
branch adds to docs, the changelog, and tests. Ids already on main are never
changed.

Dry-run is the default: it prints a mapping table and writes nothing. --apply
refuses a dirty work tree, remaps on a temporary copy, runs id and foreign-key
checks, and only then replaces files in the work tree. If a check fails, the
work tree is left unchanged. Ids already on main are never changed. Run
python scripts/build.py afterwards and commit build/. If this branch meant to
add members to a group that already exists on main, pass --keep-group <id>
(repeatable) so that group is not split. Standard library only.
"""
