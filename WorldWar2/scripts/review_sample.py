#!/usr/bin/env python3
"""Draw the reproducible review sample and compute the live counts for the review brief (standard library only).

For an outside reviewer who can only read the repository: a seeded, stratified sample of claims and of command relations, each
with the sources it cites (title, link, page or locator) so that every row can be checked against the source, plus the counts
quoted in docs/review/README.md.

Usage: python scripts/review_sample.py             write docs/review/sample.md, sample_claims.csv, sample_relations.csv and the counts block of docs/review/README.md
       python scripts/review_sample.py --check     exit 1 if any of them differs from what the current data and seed produce (the columns reviewer_verdict and reviewer_comment are ignored)
       python scripts/review_sample.py --seed N --claims 40 --relations 20     other draw (writes the same files; the committed files use the defaults)
       python scripts/review_sample.py --counts    print the counts block only

How the draw works (nothing here uses the random module, so the result is the same on every Python version and machine):
  * Every row has a rank: the SHA-256 of "<seed>:<kind>:<row id>". Lower rank = drawn first.
  * Claims: the quota per nationality is proportional to the square root of the number of claims (largest remainder, so small
    nationalities are over-sampled: the sample is for checking quality, not for estimating a rate). Inside a nationality the draw is
    coverage-first: each pick is the claim that adds the most not-yet-sampled values of echelon group, event type, confidence and claim
    status (ties by rank), so rare values are visited; once every value is covered the picks follow the rank alone.
  * Relations: the same coverage-first rule over relationship, start basis, end basis, status, the two flags (end_unknown,
    change_undated), subject nationality and whether the relation is in an overlap.
  * The sample reads build/ (run build.py first) and the master tables of data/.
  * The last two columns of the two CSV files, reviewer_verdict and reviewer_comment, are filled in by hand when a row has been checked
    against its sources (docs/review/verification_results.md). Rewriting the files keeps those two cells for every row whose sample id
    and claim or relation id are unchanged, and --check does not compare them; every other column is regenerated.
Read the result with the checklist in docs/review/checklist.md. The sample says nothing about the rows that were not drawn.
"""
import argparse
import csv
import hashlib
import json
import math
import os
import re
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402

ROOT = common.ROOT
REVIEW_DIR = os.path.join(ROOT, 'docs', 'review')
DEFAULT_SEED = 20261026
DEFAULT_CLAIMS = 40
DEFAULT_RELATIONS = 20
BEGIN, END = '<!-- counts:begin (generated by scripts/review_sample.py) -->', '<!-- counts:end -->'
BELOW_DIVISION = ('brigade', 'regiment/battle_group', 'battalion', 'other')


def rd(*parts):
    with open(os.path.join(ROOT, *parts), encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def rank(seed, kind, row_id):
    return hashlib.sha256(('%s:%s:%s' % (seed, kind, row_id)).encode('utf-8')).hexdigest()


def echelon_group(e):
    return 'below_division_or_other' if e in BELOW_DIVISION else e


def quotas(sizes, total):
    """Largest-remainder allocation proportional to sqrt(size); every stratum gets at least one and never more than its size."""
    w = {k: math.sqrt(v) for k, v in sizes.items()}
    s = sum(w.values())
    exact = {k: total * w[k] / s for k in sizes}
    q = {k: min(sizes[k], max(1, int(exact[k]))) for k in sizes}
    order = sorted(sizes, key=lambda k: (-(exact[k] - int(exact[k])), k))
    i = 0
    while sum(q.values()) < total and i < 10 * len(order):
        k = order[i % len(order)]
        if q[k] < sizes[k]:
            q[k] += 1
        i += 1
    return q


def coverage_pick(pool, n, features, ranker, covered):
    """Pick n rows of pool: each time the one adding the most uncovered feature values, ties by rank. Mutates covered."""
    pool = list(pool)
    out = []
    while pool and len(out) < n:
        best = min(pool, key=lambda r: (-sum(1 for f in features(r) if f not in covered), ranker(r)))
        pool.remove(best)
        covered.update(features(best))
        out.append(best)
    return out


# ---------------------------------------------------------------- data
def load():
    claims = rd('build', 'all_claims.csv')
    refs = {r['reference_id']: r for r in rd('data', 'references.csv')}
    links = defaultdict(list)
    for r in rd('build', 'claim_references.csv'):
        links[r['claim_id']].append(r)
    rels = rd('data', 'command_relations.csv')
    rel_claims = defaultdict(list)
    for r in rd('data', 'command_relation_claims.csv'):
        rel_claims[r['relation_id']].append(r)
    overlaps = rd('data', 'command_relation_overlaps.csv')
    units = {r['unit_id']: r for r in rd('data', 'units.csv')}
    places = {r['place_id']: r for r in rd('data', 'places.csv')}
    return dict(claims=claims, refs=refs, links=links, rels=rels, rel_claims=rel_claims, overlaps=overlaps, units=units, places=places)


def band(conf):
    return 'conf_' + conf


def claim_features(r):
    return [('echelon', echelon_group(r['echelon'])), ('event_type', r['event_type']), ('confidence', r['confidence']), ('status', r['claim_status'])]


def draw_claims(d, seed, n):
    by_nat = defaultdict(list)
    for r in d['claims']:
        by_nat[r['nationality']].append(r)
    q = quotas({k: len(v) for k, v in by_nat.items()}, n)
    covered, picked = set(), []
    for nat in sorted(by_nat, key=lambda k: (len(by_nat[k]), k)):          # smallest stratum first
        picked += coverage_pick(by_nat[nat], q[nat], claim_features, lambda r: rank(seed, 'claim', r['claim_id']), covered)
    picked.sort(key=lambda r: (r['nationality'], r['date'], r['claim_id']))
    return picked, q, covered


def rel_features(r, d, in_overlap):
    unit = d['units'].get(r['subject_unit_id'], {})
    return [('relationship', r['relationship']), ('start_basis', r['valid_from_basis']), ('end_basis', r['valid_to_basis']), ('status', r['status']),
            ('end_unknown', r['end_unknown']), ('change_undated', r['change_undated']), ('nationality', unit.get('nationality', '')),
            ('in_overlap', str(r['relation_id'] in in_overlap)), ('named_higher_unit', str(bool(r['higher_unit_id'])))]


def draw_relations(d, seed, n):
    in_overlap = {x for o in d['overlaps'] for x in (o['relation_id_a'], o['relation_id_b'])}
    covered = set()
    picked = coverage_pick(d['rels'], n, lambda r: rel_features(r, d, in_overlap), lambda r: rank(seed, 'relation', r['relation_id']), covered)
    picked.sort(key=lambda r: r['relation_id'])
    return picked, in_overlap, covered


# ---------------------------------------------------------------- output
def md_cell(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ')


def short(s, n=700):
    s = (s or '').strip()
    return s if len(s) <= n else s[:n].rstrip() + ' [...]'


def evidence_rows(d, claim_id, locator):
    out = []
    for l in d['links'].get(claim_id, []):
        ref = d['refs'].get(l['reference_id'], {})
        out.append((l['reference_id'], l['role'], ref.get('short_title', ''), ref.get('source_type', ''), ref.get('url', ''), l.get('locator') or locator or ''))
    out.sort(key=lambda x: (x[1] == 'location', x[0]))
    return out


def relationships_text(r):
    try:
        entries = json.loads(r['command_relationships'] or '[]')
    except ValueError:
        return r['command_relationships']
    return '; '.join('%s %s%s' % (e.get('relationship', ''), e.get('unit_id', ''), (' from ' + e['effective_from']) if e.get('effective_from') else '') for e in entries)


def claims_md(d, picked, q, covered, seed):
    all_vals = Counter()
    for r in d['claims']:
        for f in claim_features(r):
            all_vals[f] += 1
    kinds = defaultdict(lambda: [0, 0])
    for f in all_vals:
        kinds[f[0]][1] += 1
        if f in covered:
            kinds[f[0]][0] += 1
    out = ['## Part 1: claims (%d of %d)\n' % (len(picked), len(d['claims'])),
           'Quota per nationality (square-root allocation): ' + ', '.join('%s %d of %d' % (k, q[k], sum(1 for r in d['claims'] if r['nationality'] == k)) for k in sorted(q)) + '.',
           'Value coverage: ' + '; '.join('%s %d of %d values' % (k, v[0], v[1]) for k, v in sorted(kinds.items())) + '.\n']
    for i, r in enumerate(picked, 1):
        pl = d['places'].get(r['place_id'], {})
        out.append('### S%02d. %s: %s, %s\n' % (i, r['claim_id'], r['unit_name'] or r['unit_id'], r['date']))
        out.append('- **Unit:** %s (`%s`), %s, %s; parent in the claim: `%s`; commander field: %s' % (r['unit_name'], r['unit_id'], r['nationality'], r['echelon'], r['parent_unit_id'] or 'none', r['commander'] or 'none'))
        out.append('- **Claim:** `%s` / `%s`; status %s; confidence %s%s' % (r['event_type'], r['operation_id'] or 'no operation', r['claim_status'], r['confidence'], ('; conflict group ' + r['conflict_group_id']) if r['conflict_group_id'] else ''))
        out.append('- **Activity:** %s' % (r['current_activity'] or 'none'))
        out.append('- **Place:** %s (`%s`, %s, %s); point %s, %s%s; precision %s km; point represents: %s; qualifier: %s; coordinate source: %s' % (
            r['place_name'], r['place_id'], r['region'] or '-', r['country'] or '-', r['latitude'], r['longitude'],
            (' (claim override of the place point %s, %s)' % (pl.get('latitude'), pl.get('longitude'))) if r['coord_override'] else '', r['precision_km'], r['location_represents'] or '-',
            r['location_qualifier'] or '-', (r['coord_reference_id'] + ': ' + short(r['coord_source_note'], 160)) if r['coord_reference_id'] else short(r['coord_source_note'], 160) or '-'))
        out.append('- **Command relationships stated by the claim:** %s' % (relationships_text(r) or 'none'))
        if r['engaged_with']:
            out.append('- **Engaged with:** %s%s' % (r['engaged_with'], (' (' + short(r['engaged_note'], 200) + ')') if r['engaged_note'] else ''))
        out.append('- **Notes:** %s' % (short(r['notes']) or 'none'))
        out.append('- **Sources cited** (the claim\'s own locator: %s):\n' % (r['source_locator'] or 'none'))
        out.append('  | reference | role | title | type | link | page or locator |\n  |---|---|---|---|---|---|')
        for ref_id, role, title, typ, url, loc in evidence_rows(d, r['claim_id'], r['source_locator']):
            out.append('  | %s | %s | %s | %s | %s | %s |' % (ref_id, role, md_cell(title), typ, url, md_cell(loc)))
        out.append('')
    return out


def relations_md(d, picked, in_overlap, covered):
    out = ['## Part 2: command relations (%d of %d)\n' % (len(picked), len(d['rels'])),
           'A relation is one dated interval of one relationship between a subject unit and a higher unit. It is listed with the claims that state it (`data/command_relation_claims.csv`), what each stated, and the sources of those claims. Dates are inclusive; a blank end with `end_unknown` true means no source ends it.\n']
    names = {u: v['unit_name'] for u, v in d['units'].items()}
    for i, r in enumerate(picked, 1):
        out.append('### R%02d. %s: %s -> %s (%s)\n' % (i, r['relation_id'], names.get(r['subject_unit_id'], r['subject_unit_id']), names.get(r['higher_unit_id'], r['higher_unit_id'] or 'no higher unit named'), r['relationship']))
        out.append('- **Subject / higher unit:** `%s` / `%s`' % (r['subject_unit_id'], r['higher_unit_id'] or 'blank (unknown placeholder)'))
        out.append('- **Interval:** from %s%s (%s) to %s%s (%s); end_unknown %s; change_undated %s; date_basis %s; status %s' % (
            r['valid_from'], (' (latest ' + r['valid_from_latest'] + ')') if r['valid_from_latest'] else '', r['valid_from_basis'] or '-',
            r['valid_to'] or 'open', (' (earliest ' + r['valid_to_earliest'] + ')') if r['valid_to_earliest'] else '', r['valid_to_basis'] or '-',
            r['end_unknown'], r['change_undated'], r['date_basis'] or '-', r['status']))
        out.append('- **Note:** %s' % (short(r['note'], 500) or 'none'))
        ovs = [o for o in d['overlaps'] if r['relation_id'] in (o['relation_id_a'], o['relation_id_b'])]
        for o in ovs:
            out.append('- **Documented overlap:** %s with %s, %s to %s (%s)' % (o['relation_id_a'], o['relation_id_b'], o['overlap_from'], o['overlap_to'], o['kind']))
        out.append('- **Evidence:**\n')
        out.append('  | claim | role | stated start | stated end | what the claim stated | sources of that claim (link, locator) |\n  |---|---|---|---|---|---|---|')
        claim_by_id = {c['claim_id']: c for c in d['claims']}
        for e in sorted(d['rel_claims'].get(r['relation_id'], []), key=lambda x: int(x['seq'] or 0)):
            c = claim_by_id.get(e['claim_id'], {})
            srcs = '; '.join('%s %s%s' % (x[0], x[4], (' [' + x[5] + ']') if x[5] else '') for x in evidence_rows(d, e['claim_id'], c.get('source_locator')) if x[1] != 'location')
            out.append('  | %s (%s, %s) | %s | %s | %s | %s | %s |' % (e['claim_id'], c.get('unit_id', ''), c.get('date', ''), e['role'], e['stated_effective_from'] or '-', e['stated_effective_to'] or '-', md_cell(short(e['stated_note'], 300)), md_cell(srcs)))
        out.append('')
    return out


HEADER = """# Review sample

Generated by `python scripts/review_sample.py` (seed %(seed)d, %(nc)d claims, %(nr)d command relations). Do not edit by hand: `python scripts/review_sample.py --check` fails when this file differs from what the data and the seed produce. The rows are in `sample_claims.csv` and `sample_relations.csv` too, with `reviewer_verdict` and `reviewer_comment` columns that are filled in by hand (a fresh draw leaves them empty; the script keeps the values of unchanged rows when it rewrites the files, and `--check` ignores them). The verdicts entered so far, with the evidence, are in [verification_results.md](verification_results.md).

**What to do with a row.** Open the cited link, find the page or locator, and ask the questions in section "Sampled rows" of [checklist.md](checklist.md): does the source give this date, this place, this event, this unit and this command relationship, and is the confidence level the rubric's level? Record a problem in the findings template ([findings_template.md](findings_template.md)). A source that cannot be opened (the CMH site blocks many automated readers; some links are web archive copies) is `unverifiable`, not a finding against the row.

**How the sample was drawn.** Seeded, stratified, coverage-first (see the docstring of `scripts/review_sample.py`). It is meant to expose kinds of problems, not to measure an error rate: small nationalities and rare values are over-sampled.

"""


def kept_verdicts(name, id_col):
    """(sample_id, row id) -> (reviewer_verdict, reviewer_comment) from the committed CSV, so a rewrite keeps the hand-entered cells of unchanged rows."""
    p = os.path.join(REVIEW_DIR, name)
    if not os.path.exists(p):
        return {}
    with open(p, encoding='utf-8', newline='') as f:
        return {(r.get('sample_id', ''), r.get(id_col, '')): (r.get('reviewer_verdict') or '', r.get('reviewer_comment') or '') for r in csv.DictReader(f)}


def write_sample(d, seed, nc, nr):
    kept_c, kept_r = kept_verdicts('sample_claims.csv', 'claim_id'), kept_verdicts('sample_relations.csv', 'relation_id')
    claims, q, cov_c = draw_claims(d, seed, nc)
    rels, in_overlap, cov_r = draw_relations(d, seed, nr)
    md = HEADER % dict(seed=seed, nc=len(claims), nr=len(rels))
    md += '\n'.join(claims_md(d, claims, q, cov_c, seed) + relations_md(d, rels, in_overlap, cov_r)) + '\n'
    cols = ['sample_id', 'claim_id', 'unit_id', 'unit_name', 'nationality', 'echelon', 'date', 'event_type', 'claim_status', 'confidence', 'place_id', 'place_name', 'latitude', 'longitude', 'precision_km',
            'reference_ids', 'source_locator', 'reference_urls', 'reviewer_verdict', 'reviewer_comment']
    crows = []
    for i, r in enumerate(claims, 1):
        urls = ' '.join(x[4] for x in evidence_rows(d, r['claim_id'], r['source_locator']) if x[1] != 'location')
        crows.append(['S%02d' % i] + [r.get(c, '') for c in cols[1:15]] + [r['reference_ids'], r['source_locator'], urls] + list(kept_c.get(('S%02d' % i, r['claim_id']), ('', ''))))
    rcols = ['sample_id', 'relation_id', 'subject_unit_id', 'higher_unit_id', 'relationship', 'valid_from', 'valid_to', 'valid_from_basis', 'valid_to_basis', 'end_unknown', 'change_undated', 'status',
             'evidence_claim_ids', 'reviewer_verdict', 'reviewer_comment']
    rrows = []
    for i, r in enumerate(rels, 1):
        ev = ' '.join(e['claim_id'] for e in sorted(d['rel_claims'].get(r['relation_id'], []), key=lambda x: int(x['seq'] or 0)))
        rrows.append(['R%02d' % i] + [r[c] for c in rcols[1:12]] + [ev] + list(kept_r.get(('R%02d' % i, r['relation_id']), ('', ''))))
    return {'sample.md': md.encode('utf-8'), 'sample_claims.csv': common.csv_bytes(cols, crows), 'sample_relations.csv': common.csv_bytes(rcols, rrows)}


# ---------------------------------------------------------------- counts
def table(header, rows):
    return ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)] + ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in rows]


def counts_block(d):
    claims, units, rels = d['claims'], list(d['units'].values()), d['rels']
    C = lambda rows, k: Counter(r[k] for r in rows)
    fmt = lambda c, order=None: ', '.join('%s %d' % (k, c[k]) for k in (order or sorted(c, key=lambda x: (-c[x], x))))
    deferred = len(re.findall(r'^\| D\d+ \|', open(os.path.join(ROOT, 'docs', 'deferred_relations.md'), encoding='utf-8').read(), re.M))
    refs = rd('data', 'references.csv')
    vocab = common.load_vocabularies()
    vocab_n = sum(1 for k, v in vocab.items() if not k.startswith('_') and isinstance(v, dict) and 'values' in v)
    dates = sorted(r['date'] for r in claims)
    cg = {r['conflict_group_id'] for r in claims if r['conflict_group_id']}
    lines = [BEGIN, '']
    lines += table(['what', 'count'], [
        ['claims (rows of `data/claims/`, `build/all_claims.csv`)', '%d, dated %s to %s' % (len(claims), dates[0], dates[-1])],
        ['units in `data/units.csv`', '%d: %d active (have claims), %d placeholders' % (len(units), sum(1 for u in units if u['record_status'] == 'active'), sum(1 for u in units if u['record_status'] == 'placeholder'))],
        ['claim files (one per active unit)', len(common.claim_files())],
        ['conflict groups / claims in a group', '%d / %d' % (len(cg), sum(1 for r in claims if r['conflict_group_id']))],
        ['places (`data/places.csv`) / retired in `data/place_merges.csv`', '%d / %d' % (len(d['places']), len(rd('data', 'place_merges.csv')))],
        ['operations / operation relations', '%d / %d' % (len(rd('data', 'operations.csv')), len(rd('data', 'operation_relations.csv')))],
        ['command relations (`data/command_relations.csv`)', len(rels)],
        ['relation-to-claim evidence links (`data/command_relation_claims.csv`)', len(d['rel_claims'] and [x for v in d['rel_claims'].values() for x in v])],
        ['documented relation overlaps (`data/command_relation_overlaps.csv`)', len(d['overlaps'])],
        ['deferred relations (`docs/deferred_relations.md`, ids D01 onward)', deferred],
        ['references (`data/references.csv`, generated)', '%d, of which %d cited by at least one claim (the others are cited by units or operations)' % (len(refs), sum(1 for r in refs if r['claims_count'] != '0'))],
        ['claim-reference roles (`data/claim_reference_roles.csv`)', len(rd('data', 'claim_reference_roles.csv'))],
        ['nationalities / retired claim ids / claim-key exceptions', '%d / %d / %d' % (len(rd('data', 'nationalities.csv')), len(rd('data', 'retired_claims.csv')), len(rd('data', 'claim_key_exceptions.csv')))],
        ['controlled vocabularies in `schema/vocabularies.json`', vocab_n],
    ])
    lines += ['', 'Claims by nationality: %s.' % fmt(C(claims, 'nationality')), '',
              'Claims by echelon: %s.' % fmt(C(claims, 'echelon')), '',
              'Claims by branch: %s.' % fmt(C(claims, 'branch')), '',
              'Claims by event type: %s.' % fmt(C(claims, 'event_type')), '',
              'Claims by status: %s. Claims by confidence: %s.' % (fmt(C(claims, 'claim_status')), fmt(C(claims, 'confidence'), sorted(C(claims, 'confidence')))), '',
              'Placeholder units by nationality: %s.' % fmt(Counter(u['nationality'] for u in units if u['record_status'] == 'placeholder')), '',
              'Command relations by relationship: %s.' % fmt(C(rels, 'relationship')), '',
              'Command relations: start basis %s; end basis %s; `end_unknown` true %d; `change_undated` true %d; status %s.' % (
                  fmt(C(rels, 'valid_from_basis')), fmt(C(rels, 'valid_to_basis')), sum(1 for r in rels if r['end_unknown'] == 'true'), sum(1 for r in rels if r['change_undated'] == 'true'), fmt(C(rels, 'status'))), '',
              'Evidence roles of relation links: %s.' % fmt(Counter(x['role'] for v in d['rel_claims'].values() for x in v)), '',
              'References by source family: %s; by type: %s.' % (fmt(C(refs, 'source_family')), fmt(C(refs, 'source_type'))), '',
              'Places by kind: %s.' % fmt(Counter(p['kind'] for p in d['places'].values())), '', END]
    return '\n'.join(lines)


def readme_with_counts(d):
    p = os.path.join(REVIEW_DIR, 'README.md')
    text = open(p, encoding='utf-8').read()
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < 0:
        raise SystemExit('docs/review/README.md has no counts markers (%s ... %s)' % (BEGIN, END))
    return (text[:i] + counts_block(d) + text[j + len(END):]).encode('utf-8')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--seed', type=int, default=DEFAULT_SEED)
    ap.add_argument('--claims', type=int, default=DEFAULT_CLAIMS)
    ap.add_argument('--relations', type=int, default=DEFAULT_RELATIONS)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--counts', action='store_true')
    a = ap.parse_args()
    d = load()
    if a.counts:
        print(counts_block(d))
        return 0
    files = write_sample(d, a.seed, a.claims, a.relations)
    if os.path.exists(os.path.join(REVIEW_DIR, 'README.md')):
        files['README.md'] = readme_with_counts(d)
    stale = []
    for name, data in sorted(files.items()):
        p = os.path.join(REVIEW_DIR, name)
        cur = open(p, 'rb').read() if os.path.exists(p) else None
        if a.check:
            if cur != data:
                stale.append(name)
        elif cur != data:
            os.makedirs(REVIEW_DIR, exist_ok=True)
            with open(p, 'wb') as f:
                f.write(data)
            print('wrote docs/review/' + name)
    if a.check:
        if stale:
            print('docs/review is stale (%s); run python scripts/review_sample.py, then python scripts/build.py, and commit both' % ', '.join(stale))
            return 1
        print('OK: docs/review sample and counts are up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
