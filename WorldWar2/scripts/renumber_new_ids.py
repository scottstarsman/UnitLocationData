def num(s):
    i = 0
    while i < len(s) and not s[i].isdigit():
        i += 1
    return int(s[i:]) if i < len(s) else 0


def format_id(prefix, width, n):
    return '%s%0*d' % (prefix, width, n)


def identity_of(row, cols):
    return tuple((row.get(c) or '').strip() for c in cols)


def git(root, *args):
    p = subprocess.run(['git'] + list(args), capture_output=True, text=True, cwd=root)
    return p.returncode, p.stdout, p.stderr


def git_prefix(root):
    rc, out, err = git(root, 'rev-parse', '--show-prefix')
    if rc:
        raise SystemExit('not inside a git work tree: %s' % (err or '').strip())
    return out.strip()


def git_show(root, rev, rel_path, optional=False):
    prefix = git_prefix(root)
    rc, out, err = git(root, 'show', '%s:%s%s' % (rev, prefix, rel_path.replace(os.sep, '/')))
    if rc:
        if optional:
            return None
        raise SystemExit('cannot read %s at %s: %s' % (rel_path, rev, (err or '').strip()))
    return out


def read_csv_text(txt):
    if not txt:
        return [], []
    rd = csv.DictReader(io.StringIO(txt))
    header = list(rd.fieldnames or [])
    return header, list(rd)


def read_csv_path(path):
    if not os.path.isfile(path):
        return [], []
    return common.read_dicts(path)


def glob_rel(root, pattern):
    import glob
    out = []
    for p in sorted(glob.glob(os.path.join(root, pattern))):
        if os.path.isfile(p):
            out.append(os.path.relpath(p, root))
    return out


def table_paths(root, pattern):
    if any(ch in pattern for ch in '*?['):
        return glob_rel(root, pattern)
    path = os.path.join(root, pattern)
    return [pattern] if os.path.isfile(path) else []


def load_base_rows(root, rev, rel_path):
    txt = git_show(root, rev, rel_path, optional=True)
    if txt is None:
        return [], []
    return read_csv_text(txt)


def iter_table_rows(root, rev, pattern, from_working=True):
    """Yield (rel_path, row) for a table glob, from the working tree or from git."""
    if from_working:
        for rel in table_paths(root, pattern):
            _h, rows = read_csv_path(os.path.join(root, rel))
            for row in rows:
                yield rel, row
        return
    if not from_working and pattern in BASE_AGGREGATES:
        found = False
        for agg in BASE_AGGREGATES[pattern]:
            _h, rows = load_base_rows(root, rev, agg)
            if not rows:
                continue
            found = True
            for row in rows:
                yield agg, row
        if found:
            return
    # From git: expand paths from the working tree plus any the glob would match
    # at <rev> via git ls-files / ls-tree on the pattern prefix.
    prefix = git_prefix(root)
    if any(ch in pattern for ch in '*?['):
        # List files at rev under the first directory of the pattern.
        top = pattern.split(os.sep)[0] if os.sep in pattern else pattern
        rc, out, _ = git(root, 'ls-tree', '-r', '--name-only', rev, prefix + top)
        want = re.compile(fnmatch_to_re(prefix + pattern.replace(os.sep, '/')))
        rels = []
        for line in (out or '').splitlines():
            if not want.match(line):
                continue
            rels.append(line[len(prefix):] if line.startswith(prefix) else line)
    else:
        rels = [pattern]
    seen = set()
    for rel in rels:
        rel = rel.replace('/', os.sep)
        if rel in seen:
            continue
        seen.add(rel)
        _h, rows = load_base_rows(root, rev, rel)
        for row in rows:
            yield rel, row


def fnmatch_to_re(pattern):
    # pattern uses / as separator and fnmatch * **
    parts = []
    i = 0
    while i < len(pattern):
        c = pattern[i]
        if c == '*':
            parts.append(r'[^/]*')
            i += 1
        elif c == '?':
            parts.append(r'[^/]')
            i += 1
        else:
            parts.append(re.escape(c))
            i += 1
    return r'^' + ''.join(parts) + r'$'


def used_ids_for_prefix(root, rev, prefix):
    """All ids of one prefix in the base revision and the working tree, including retired."""
    used = set()
    for kind, pfx, width, pattern, id_col, _ident in TABLES:
        if pfx != prefix:
            continue
        for _rel, row in iter_table_rows(root, rev, pattern, from_working=True):
            i = (row.get(id_col) or '').strip()
            if i:
                used.add(i)
        for _rel, row in iter_table_rows(root, rev, pattern, from_working=False):
            i = (row.get(id_col) or '').strip()
            if i:
                used.add(i)
    for rel, col, pfx, _w in RETIRED:
        if pfx != prefix:
            continue
        for src in (True, False):
            if src:
                _h, rows = read_csv_path(os.path.join(root, rel)) if os.path.isfile(os.path.join(root, rel)) else ([], [])
            else:
                _h, rows = load_base_rows(root, rev, rel)
            for row in rows:
                i = (row.get(col) or '').strip()
                if i:
                    used.add(i)
    if prefix == 'G':
        for i in collect_groups(root, working=True).keys():
            used.add(i)
        for i in collect_groups_from_base(root, rev).keys():
            used.add(i)
    return used


def collect_groups_from_rows(items):
    """items: iterable of (id, conflict_group_id)."""
    groups = {}
    for mid, g in items:
        g = (g or '').strip()
        mid = (mid or '').strip()
        if g and mid:
            groups.setdefault(g, set()).add(mid)
    return groups


def _group_members_from_tree(root, working, rev=None):
    items = []
    specs = [
        (os.path.join('data', 'claims', '*', '*.csv'), 'claim_id'),
        (os.path.join('data', 'missions', '*', '*.csv'), 'mission_id'),
        (os.path.join('data', 'unit_commanders.csv'), 'tenure_id'),
    ]
    for pattern, id_col in specs:
        for _rel, row in iter_table_rows(root, rev or 'HEAD', pattern, from_working=working):
            items.append(((row.get(id_col) or '').strip(), (row.get('conflict_group_id') or '').strip()))
    return collect_groups_from_rows(items)


def collect_groups(root, working=True):
    return _group_members_from_tree(root, True, 'HEAD')


def collect_groups_from_base(root, rev):
    return _group_members_from_tree(root, False, rev)


def next_free(used, prefix, width):
    top = 0
    for i in used:
        if i.startswith(prefix) and i[len(prefix):].isdigit():
            top = max(top, int(i[len(prefix):]))
    return top + 1


def allocate(used, prefix, width):
    n = next_free(used, prefix, width)
    new = format_id(prefix, width, n)
    used.add(new)
    return new


def plan_table_collisions(root, rev):
    """Return (mappings list of dicts, problems, base_ids by prefix, new_row_ids)."""
    mappings = []
    problems = []
    new_ids = set()  # primary ids of rows that are new or being remapped
    for kind, prefix, width, pattern, id_col, ident_cols in TABLES:
        base = {}  # id -> identity
        base_paths = {}  # id -> rel path
        for rel, row in iter_table_rows(root, rev, pattern, from_working=False):
            i = (row.get(id_col) or '').strip()
            if not i:
                continue
            base[i] = identity_of(row, ident_cols)
            base_paths[i] = rel
        work = {}  # id -> list of (rel, row, identity)
        for rel, row in iter_table_rows(root, rev, pattern, from_working=True):
            i = (row.get(id_col) or '').strip()
            if not i:
                continue
            work.setdefault(i, []).append((rel, row, identity_of(row, ident_cols)))
        for i, rows in work.items():
            if i not in base:
                new_ids.add(i)
                if len(rows) > 1:
                    # Duplicate new id: keep the first path/identity, remumber the rest.
                    kept = rows[0][2]
                    for rel, row, ident in rows[1:]:
                        mappings.append({
                            'kind': kind, 'prefix': prefix, 'width': width,
                            'old': i, 'rel': rel, 'identity': ident,
                            'reason': 'duplicate new %s id on this branch (kept the first row)' % kind,
                            'id_col': id_col,
                        })
                continue
            matching = [t for t in rows if t[2] == base[i]]
            colliding = [t for t in rows if t[2] != base[i]]
            if colliding and not matching:
                if len(colliding) == 1:
                    problems.append(
                        '%s %s is on %s as %s, but this branch has it as %s and the published row is missing. '
                        'Restore the published row, then rerun; not remapped.' % (
                            kind, i, rev, '/'.join(base[i]), '/'.join(colliding[0][2]))
                    )
                else:
                    problems.append(
                        '%s %s has several rows on this branch, none matching %s (%s). Not remapped.' % (
                            kind, i, rev, '/'.join(base[i]))
                    )
                continue
            for rel, row, ident in colliding:
                mappings.append({
                    'kind': kind, 'prefix': prefix, 'width': width,
                    'old': i, 'rel': rel, 'identity': ident,
                    'reason': 'id already on %s for %s' % (rev, '/'.join(base[i]) or '(blank)'),
                    'id_col': id_col,
                })
                # Mark this unpublished use as new (the old id is published for someone else).
    return mappings, problems, new_ids


def assign_new_ids(root, rev, mappings):
    """Fill mapping['new'] using next free ids. mappings may share the same old id."""
    used_by_prefix = {}
    for m in mappings:
        pfx = m['prefix']
        if pfx not in used_by_prefix:
            used_by_prefix[pfx] = used_ids_for_prefix(root, rev, pfx)
        m['new'] = allocate(used_by_prefix[pfx], pfx, m['width'])


def member_row_is_new(rel, row, id_col, base_members, mappings):
    """True if this claim/mission/tenure row is unpublished on this branch."""
    i = (row.get(id_col) or '').strip()
    if not i:
        return False
    if i not in base_members:
        return True
    for m in mappings:
        if m['prefix'] not in ('C', 'MSN', 'UC'):
            continue
        if m.get('scope') in ('new_members', 'added_lines'):
            continue
        if m['old'] != i or m['rel'] != rel:
            continue
        ident_cols = None
        for t in TABLES:
            if t[0] == m['kind'] and t[4] == id_col:
                ident_cols = t[5]
                break
        if ident_cols is None or identity_of(row, ident_cols) == tuple(m['identity']):
            return True
    return False


def plan_group_splits(root, rev, mappings, keep_groups):
    """Renumber G ids on new members that would silently join a base group."""
    base_members = collect_base_members(root, rev)
    base_groups = collect_groups_from_base(root, rev)
    work_by_g = {}
    for pattern, id_col in (
        (os.path.join('data', 'claims', '*', '*.csv'), 'claim_id'),
        (os.path.join('data', 'missions', '*', '*.csv'), 'mission_id'),
        (os.path.join('data', 'unit_commanders.csv'), 'tenure_id'),
    ):
        for rel, row in iter_table_rows(root, rev, pattern, from_working=True):
            i = (row.get(id_col) or '').strip()
            g = (row.get('conflict_group_id') or '').strip()
            if not g or not i:
                continue
            is_new = member_row_is_new(rel, row, id_col, base_members, mappings)
            work_by_g.setdefault(g, []).append((rel, i, is_new))

    used_g = used_ids_for_prefix(root, rev, 'G')
    for m in mappings:
        if m.get('prefix') == 'G':
            used_g.add(m.get('new') or m['old'])

    extra = []
    for g, members in sorted(work_by_g.items(), key=lambda kv: num(kv[0])):
        if g in keep_groups:
            continue
        if g not in base_groups:
            continue
        new_members = [t for t in members if t[2]]
        if not new_members:
            continue
        new_id = allocate(used_g, 'G', 3)
        # One mapping per group, applied to all new members of g.
        extra.append({
            'kind': 'conflict group',
            'prefix': 'G',
            'width': 3,
            'old': g,
            'new': new_id,
            'rel': ', '.join(sorted({t[0] for t in new_members})),
            'identity': tuple(sorted({t[1] for t in new_members})),
            'reason': (
                'new rows on this branch use %s, which already exists on %s; '
                'they would silently join that group. If that was intended, rerun with --keep-group %s'
                % (g, rev, g)
            ),
            'id_col': 'conflict_group_id',
            'scope': 'new_members',
        })
    return extra


def read_text(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def plan_scenario_collisions(root, rev):
    rel = os.path.join('scripts', 'semantic_tests.py')
    base_txt = git_show(root, rev, rel, optional=True) or ''
    work_path = os.path.join(root, rel)
    if not os.path.isfile(work_path):
        return [], set()
    work_txt = read_text(work_path)
    base_nums = {int(n) for n in SCENARIO_DEF_RE.findall(base_txt)}
    added = added_line_numbers(root, rev, rel)
    mappings = []
    used = set(base_nums)
    used.update(int(n) for n in SCENARIO_DEF_RE.findall(work_txt))
    # For each added def scenario_N_ whose N is already on the base, remumber.
    seen = set()
    for m in SCENARIO_DEF_RE.finditer(work_txt):
        n = int(m.group(1))
        # 1-based line number
        line_no = work_txt[:m.start()].count('\n') + 1
        if line_no not in added:
            continue
        if n not in base_nums:
            continue
        if n in seen:
            continue
        seen.add(n)
        nxt = max(used) + 1 if used else 1
        used.add(nxt)
        mappings.append({
            'kind': 'scenario',
            'prefix': 'scenario',
            'width': 0,
            'old': 'scenario %d' % n,
            'new': 'scenario %d' % nxt,
            'old_n': n,
            'new_n': nxt,
            'rel': rel,
            'identity': (m.group(0),),
            'reason': 'scenario %d already exists on %s' % (n, rev),
            'id_col': None,
            'scope': 'added_lines',
        })
    return mappings, added


def plan_roadmap_collisions(root, rev):
    rel = os.path.join('docs', 'roadmap.md')
    base_txt = git_show(root, rev, rel, optional=True) or ''
    work_path = os.path.join(root, rel)
    if not os.path.isfile(work_path):
        return []
    work_txt = read_text(work_path)
    base_nums = {int(n) for n in ROADMAP_ITEM_RE.findall(base_txt)}
    added = added_line_numbers(root, rev, rel)
    used = set(base_nums)
    used.update(int(n) for n in ROADMAP_ITEM_RE.findall(work_txt))
    mappings = []
    seen = set()
    lines = work_txt.splitlines()
    for idx, line in enumerate(lines, 1):
        if idx not in added:
            continue
        m = re.match(r'^(\d+)\. ', line)
        if not m:
            continue
        n = int(m.group(1))
        if n not in base_nums or n in seen:
            continue
        seen.add(n)
        nxt = max(used) + 1 if used else 1
        used.add(nxt)
        mappings.append({
            'kind': 'roadmap',
            'prefix': 'roadmap',
            'width': 0,
            'old': 'roadmap %d' % n,
            'new': 'roadmap %d' % nxt,
            'old_n': n,
            'new_n': nxt,
            'rel': rel,
            'identity': (line[:80],),
            'reason': 'roadmap item %d already exists on %s' % (n, rev),
            'id_col': None,
            'scope': 'added_lines',
        })
    return mappings


def added_line_numbers(root, rev, rel):
    """1-based line numbers in the working tree that this branch adds versus <rev>."""
    # git() uses cwd=root, so pathspecs must be relative to the dataset root,
    # not prefixed with the path from the repository root (that form is only
    # valid in 'git show rev:WorldWar2/...' object names).
    pathspec = rel.replace(os.sep, '/')
    rc, out, err = git(root, 'diff', '-U0', rev, '--', pathspec)
    if rc and not out:
        # Untracked file: every line is added.
        path = os.path.join(root, rel)
        if os.path.isfile(path):
            # Check whether git knows the file
            rc2, out2, _ = git(root, 'ls-files', '--', pathspec)
            if not (out2 or '').strip():
                n = read_text(path).count('\n')
                # If file does not end with newline, last line still counts
                if os.path.getsize(path) and not read_text(path).endswith('\n'):
                    n += 1
                return set(range(1, n + 1))
        return set()
    added = set()
    hunk = re.compile(r'^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@')
    for line in (out or '').splitlines():
        m = hunk.match(line)
        if m:
            start = int(m.group(1))
            count = int(m.group(2) or '1')
            if count == 0:
                continue
            for n in range(start, start + count):
                added.add(n)
    return added


def plan(root, rev, keep_groups=None):
    keep_groups = set(keep_groups or [])
    mappings, problems, _new_ids = plan_table_collisions(root, rev)
    assign_new_ids(root, rev, mappings)
    mappings.extend(plan_group_splits(root, rev, mappings, keep_groups))
    scen, _ = plan_scenario_collisions(root, rev)
    mappings.extend(scen)
    mappings.extend(plan_roadmap_collisions(root, rev))
    return mappings, problems


def token_map(mappings):
    """old token -> new token for prefixed ids (not scenario/roadmap)."""
    out = {}
    for m in mappings:
        if m['prefix'] in ('scenario', 'roadmap'):
            continue
        out[m['old']] = m['new']
    return out


def replace_tokens(text, tmap):
    if not tmap or not text:
        return text

    def repl(match):
        return tmap.get(match.group(1), match.group(0))

    return ID_TOKEN_RE.sub(repl, text)


def replace_scenario_roadmap(text, mappings, only_kinds=None):
    out = text
    # Longer / larger numbers first so 368 is not caught inside a later 36 replace
    # (tokens are bounded, but still apply most-specific first).
    items = [m for m in mappings if m['prefix'] in (only_kinds or ('scenario', 'roadmap'))]
    items.sort(key=lambda m: -m.get('old_n', 0))
    for m in items:
        n, nxt = m['old_n'], m['new_n']
        if m['prefix'] == 'scenario':
            # scenario_368_name has no word break after the number.
            out = re.sub(r'\bscenario_%d(?=_)' % n, 'scenario_%d' % nxt, out)
            out = re.sub(r'\bscenario %d\b' % n, 'scenario %d' % nxt, out)
        else:
            out = re.sub(r'\broadmap %d\b' % n, 'roadmap %d' % nxt, out)
            out = re.sub(r'(?m)^%d\. ' % n, '%d. ' % nxt, out)
    return out


def row_tuple(header, row):
    return tuple((row.get(c) or '') for c in header)


def apply_csv_file(root, rel, header, rows, base_header, base_rows, mappings, tmap, base_members):
    """Return new rows and whether anything changed."""
    if not header:
        return rows, False
    base_set = {row_tuple(base_header or header, r) for r in base_rows}
    base_counts = Counter(row_tuple(base_header or header, r) for r in base_rows)
    seen_counts = Counter()
    table_maps = [
        m for m in mappings
        if m.get('scope') not in ('new_members', 'added_lines') and m.get('rel') == rel
    ]
    group_maps = [m for m in mappings if m.get('scope') == 'new_members']

    def ident_cols_for(kind, col):
        for t in TABLES:
            if t[0] == kind and t[4] == col:
                return t[5]
        return None

    changed = False
    out = []
    for row in rows:
        row = dict(row)
        original = row_tuple(header, row)
        orig_row = dict(zip(header, original))
        row_tmap = dict(tmap)
        was_colliding = False
        for m in table_maps:
            col = m['id_col']
            if not col or (row.get(col) or '').strip() != m['old']:
                continue
            ident_cols = ident_cols_for(m['kind'], col)
            if ident_cols and m.get('identity') and identity_of(row, ident_cols) != tuple(m['identity']):
                continue
            row[col] = m['new']
            row_tmap[m['old']] = m['new']
            was_colliding = m['prefix'] in ('C', 'MSN', 'UC')
            changed = True

        primary = (
            (row.get('claim_id') or row.get('mission_id') or row.get('tenure_id') or '').strip()
        )
        is_new_member = was_colliding or (primary and primary not in base_members)
        g = (row.get('conflict_group_id') or '').strip()
        if g and is_new_member:
            for m in group_maps:
                if g == m['old']:
                    row['conflict_group_id'] = m['new']
                    row_tmap[m['old']] = m['new']
                    changed = True
                    break

        seen_counts[original] += 1
        # A new row can be token-identical to a published link (both sides collided).
        # Extra copies of a published tuple are unpublished and must be remapped.
        is_new_row = (original not in base_set) or (seen_counts[original] > base_counts[original])
        if is_new_row:
            for c in header:
                val = row.get(c) or ''
                if not val:
                    continue
                new_val = replace_tokens(val, row_tmap)
                new_val = replace_scenario_roadmap(new_val, mappings)
                if new_val != val:
                    row[c] = new_val
                    changed = True
        out.append(row)
    return out, changed


def write_csv(path, header, rows):
    data = common.csv_bytes(header, [[r.get(c, '') for c in header] for r in rows])
    # Preserve a trailing newline (csv_bytes already ends with \n after last row)
    with open(path, 'wb') as f:
        f.write(data)


def apply_text_file(path, added_lines, tmap, mappings):
    text = read_text(path)
    lines = text.splitlines(keepends=True)
    changed = False
    out = []
    for idx, line in enumerate(lines, 1):
        if idx in added_lines:
            new = replace_tokens(line, tmap)
            new = replace_scenario_roadmap(new, mappings)
            if new != line:
                changed = True
                line = new
        out.append(line)
    if changed:
        with open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(''.join(out))
    return changed


def working_and_base_csv_paths(root, rev):
    """All data CSV paths to consider, from the working tree."""
    out = []
    data_root = os.path.join(root, 'data')
    if not os.path.isdir(data_root):
        return out
    for dirpath, dirnames, filenames in os.walk(data_root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIR_PARTS]
        for fn in filenames:
            if not fn.endswith('.csv'):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), root)
            if rel.replace(os.sep, '/') in {p.replace(os.sep, '/') for p in SKIP_CSV}:
                continue
            out.append(rel)
    return sorted(out)


def is_text_rewrite_target(rel):
    """Only docs, dataset READMEs/CONTRIBUTING, and semantic_tests.py get token rewrites.

    Other Python (this script, tests, tools) may mention ids as examples; rewriting
    them would corrupt the tools. Data CSVs are handled row by row, not here.
    """
    rel = rel.replace(os.sep, '/')
    if rel.startswith('docs/'):
        return True
    if rel in ('CONTRIBUTING.md', 'README.md'):
        return True
    if rel == 'scripts/semantic_tests.py':
        return True
    return False


def changed_text_files(root, rev):
    """Docs, CONTRIBUTING/README, and semantic_tests.py this branch adds or edits."""
    prefix = git_prefix(root)
    rc, out, _ = git(root, 'diff', '--name-only', '--diff-filter=ACMR', rev)
    candidates = list((out or '').splitlines())
    rc, out, _ = git(root, 'ls-files', '--others', '--exclude-standard')
    candidates.extend((out or '').splitlines())
    names = []
    seen = set()
    for line in candidates:
        if not line:
            continue
        rel = line
        if prefix and rel.startswith(prefix):
            rel = rel[len(prefix):]
        rel = rel.replace('/', os.sep)
        if rel in seen or rel.split(os.sep)[0] in SKIP_DIR_PARTS:
            continue
        if not is_text_rewrite_target(rel):
            continue
        if os.path.isfile(os.path.join(root, rel)):
            seen.add(rel)
            names.append(rel)
    return names


def collect_base_members(root, rev):
    members = set()
    for pattern, id_col in (
        (os.path.join('data', 'claims', '*', '*.csv'), 'claim_id'),
        (os.path.join('data', 'missions', '*', '*.csv'), 'mission_id'),
        (os.path.join('data', 'unit_commanders.csv'), 'tenure_id'),
    ):
        for _rel, row in iter_table_rows(root, rev, pattern, from_working=False):
            i = (row.get(id_col) or '').strip()
            if i:
                members.add(i)
    return members


def apply_all(root, rev, mappings):
    tmap = token_map(mappings)
    base_members = collect_base_members(root, rev)
    written = []
    for rel in working_and_base_csv_paths(root, rev):
        path = os.path.join(root, rel)
        header, rows = read_csv_path(path)
        if not header:
            continue
        b_header, b_rows = load_base_rows(root, rev, rel)
        new_rows, changed = apply_csv_file(root, rel, header, rows, b_header, b_rows, mappings, tmap, base_members)
        if changed:
            write_csv(path, header, new_rows)
            written.append(rel)
    for rel in changed_text_files(root, rev):
        added = added_line_numbers(root, rev, rel)
        if not added:
            continue
        path = os.path.join(root, rel)
        if apply_text_file(path, added, tmap, mappings):
            written.append(rel)
    return written


def print_table(mappings, problems, apply=False):
    if problems:
        for p in problems:
            print('PROBLEM:', p)
    if not mappings:
        print('No colliding unpublished ids.')
        return
    cols = ('kind', 'old', 'new', 'reason')
    rows = []
    for m in mappings:
        rows.append((m['kind'], m['old'], m['new'], m['reason']))
    widths = [max(len(c), max(len(r[i]) for r in rows)) for i, c in enumerate(cols)]
    # cap reason width for readability
    widths[3] = min(widths[3], 100)
    fmt = '  '.join('%%-%ds' % w for w in widths)
    print(fmt % cols)
    print('  '.join('-' * w for w in widths))
    for r in rows:
        reason = r[3] if len(r[3]) <= 100 else r[3][:97] + '...'
        print(fmt % (r[0], r[1], r[2], reason))
    print('%d mapping(s).' % len(mappings))
    if not apply:
        print('Dry-run only; rerun with --apply to write these remappings. Then run python scripts/build.py and commit build/.')


